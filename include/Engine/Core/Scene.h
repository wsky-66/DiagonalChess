#pragma once

// ===================================================================
// Scene.h — 场景类的抽象基类
// 场景是游戏中最上层的抽象，代表一个可独立运行的"画面"
// 比如：主菜单是一个场景，对战游戏是另一个场景
// 每个场景必须实现 Update（更新逻辑）和 Render（渲染画面）
// ===================================================================

class Scene {
public:
    virtual ~Scene() = default;     // 虚析构函数

    // 每帧调用：更新游戏逻辑
    // dt = 上一帧到这一帧经过的时间（秒），用于让动画与帧率无关
    virtual void Update(float dt) = 0;

    // 每帧调用：绘制当前场景的所有内容到窗口
    virtual void Render() = 0;
};
